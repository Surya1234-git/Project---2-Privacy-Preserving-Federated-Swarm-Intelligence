#!/usr/bin/env python3
"""Generate docker-compose.yml for an N-node swarm straight from the shard manifest.

    python scripts/gen_compose.py --shards data/shards --mode fhe --out docker-compose.yml

What makes this a *swarm* and not N copies of one container:
  * every node gets its own device class -> its own CPU / memory ceiling (phone, iot, gateway)
  * every node mounts exactly ONE shard file, read-only (no node can read another's data)
  * nodes run read-only, non-root, with all Linux capabilities dropped and a PID limit
  * the aggregator mounts only the PUBLIC key volume; nodes mount only the SECRET one
  * the node's device class + its manifest row are the single source of truth for behaviour
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from swarm.profiles import DEVICE_PROFILES  # noqa: E402


def render(manifest: dict, shards_dir: str, mode: str, rounds: int, participation: float,
           time_scale: float, port: int) -> str:
    n = manifest["n_nodes"]
    env_common = {
        "SWARM_MODE": mode, "SWARM_ROUNDS": rounds, "SWARM_PARTICIPATION": participation,
        "SWARM_INPUT_DIM": manifest["input_dim"], "SWARM_NUM_CLASSES": manifest["num_classes"],
        "SWARM_ENROLL_SECRET": "${SWARM_ENROLL_SECRET:-dev-enroll-secret-change-me}",
    }
    L = ["# GENERATED by scripts/gen_compose.py - do not edit by hand; regenerate instead.",
         f"# {n} edge nodes | mode={mode} | dataset={manifest['dataset']} | "
         f"non-IID score={manifest['heterogeneity']['noniid_score']:.3f}",
         "name: swarmshield", "", "x-node-hardening: &hardening",
         "  read_only: true", "  user: \"10001:10001\"", "  cap_drop: [ALL]",
         "  security_opt: [\"no-new-privileges:true\"]", "  pids_limit: 64",
         "  tmpfs: [/tmp]", "  restart: \"no\"", "  networks: [swarm]", "",
         "services:"]
    if mode == "fhe":
        L += ["  keygen:",
              "    build: .", "    image: swarmshield:latest",
              "    command: python -m swarm.crypto.keygen --public /keys-public/public.ctx "
              "--secret /keys-secret/secret.ctx",
              "    user: \"0:0\"", "    environment:", "      SWARM_KEYS_WORLD_READABLE: \"1\"",
              "    volumes:", "      - keys_public:/keys-public", "      - keys_secret:/keys-secret",
              "    networks: [swarm]", ""]
    L += ["  aggregator:", "    build: .", "    image: swarmshield:latest",
          "    command: python -m swarm.server.main", "    environment:"]
    for k, v in {**env_common, "SWARM_EXPECTED_NODES": n, "SWARM_PORT": 8080,
                 "SWARM_OUT_DIR": "/runs/latest", "SWARM_EXIT_WHEN_DONE": 1,
                 **({"SWARM_PUBLIC_CTX": "/keys/public.ctx"} if mode == "fhe" else {})}.items():
        L.append(f"      {k}: \"{v}\"")
    L += ["    volumes:", "      - ./runs:/runs"]
    if mode == "fhe":
        L += ["      - keys_public:/keys:ro"]          # PUBLIC key volume only
    L += ["    ports:", f"      - \"{port}:8080\"", "    user: \"10001:10001\"",
          "    cap_drop: [ALL]", "    security_opt: [\"no-new-privileges:true\"]",
          "    networks: [swarm]",
          "    healthcheck:",
          "      test: [\"CMD\", \"python\", \"-c\", \"import urllib.request as u; "
          "u.urlopen('http://localhost:8080/healthz')\"]",
          "      interval: 3s", "      timeout: 3s", "      retries: 20"]
    if mode == "fhe":
        L += ["    depends_on:", "      keygen: {condition: service_completed_successfully}"]
    L.append("")

    for node in manifest["nodes"]:
        p = DEVICE_PROFILES[node["device_class"]]
        nid = node["node_id"]
        L += [f"  {nid}:", "    build: .", "    image: swarmshield:latest",
              "    command: python -m swarm.node.client", "    <<: *hardening",
              f"    cpus: {p.cpus}", f"    mem_limit: {p.mem_mb}m", "    environment:"]
        env = {**env_common, "SWARM_NODE_ID": nid, "SWARM_DEVICE_CLASS": node["device_class"],
               "SWARM_SHARD": "/data/shard.npz", "SWARM_SERVER_URL": "http://aggregator:8080",
               "SWARM_TIME_SCALE": time_scale,
               **({"SWARM_SECRET_CTX": "/keys/secret.ctx"} if mode == "fhe" else {})}
        L += [f"      {k}: \"{v}\"" for k, v in env.items() if k not in
              ("SWARM_ROUNDS", "SWARM_PARTICIPATION", "SWARM_MODE", "SWARM_INPUT_DIM",
               "SWARM_NUM_CLASSES")]
        L += ["    volumes:", f"      - ./{shards_dir}/{nid}.npz:/data/shard.npz:ro"]
        if mode == "fhe":
            L += ["      - keys_secret:/keys:ro"]      # SECRET key volume: nodes only
        L += ["    depends_on:", "      aggregator: {condition: service_healthy}", ""]

    L += ["networks:", "  swarm: {}", ""]
    if mode == "fhe":
        L += ["volumes:", "  keys_public: {}", "  keys_secret: {}", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--shards", default="data/shards")
    ap.add_argument("--mode", choices=["plain", "fhe"], default="fhe")
    ap.add_argument("--rounds", type=int, default=15)
    ap.add_argument("--participation", type=float, default=0.3)
    ap.add_argument("--time-scale", type=float, default=0.1,
                    help="multiplier on emulated compute/network delays (1.0 = full realism)")
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--out", default="docker-compose.yml")
    a = ap.parse_args()
    manifest = json.loads((Path(a.shards) / "manifest.json").read_text())
    Path(a.out).write_text(render(manifest, a.shards, a.mode, a.rounds, a.participation,
                                  a.time_scale, a.port))
    print(f"wrote {a.out}: {manifest['n_nodes']} nodes, mode={a.mode}")


if __name__ == "__main__":
    main()
